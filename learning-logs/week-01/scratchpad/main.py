# Kita akan menghitung tegangan (stress) sederhana layaknya di Teknik Mesin.

# 1. Variabel (Menyimpan data)
gaya = 5000  # Gaya dalam Newton (N)
luas_penampang = 0.05  # Luas dalam meter persegi (m^2)

# 2. Operasi Matematika
tegangan = gaya / luas_penampang

# 3. Menampilkan hasil
print("Halo Raihan, ini script Python pertamamu!")
print(f"Gaya yang diberikan: {gaya} N")
print(f"Luas penampang: {luas_penampang} m^2")
print(f"Tegangan yang dihasilkan: {tegangan} N/m^2 (Pascal)")